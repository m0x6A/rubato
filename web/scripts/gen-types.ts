/**
 * Generate `src/protocol.ts` from `schema/protocol/*.schema.json` (the `web-server` seam).
 * All schemas share their `$defs`, so they are merged into one root and compiled once; CI
 * diffs the result against the committed file.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile, type JSONSchema } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(here, "../../schema/protocol");
const out = resolve(here, "../src/protocol.ts");

const defs: Record<string, JSONSchema> = {};
const roots: Record<string, JSONSchema> = {};
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort()) {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf8")) as JSONSchema & { $defs?: Record<string, JSONSchema>; title?: string };
  const title = schema.title ?? file.replace(".schema.json", "");
  for (const [name, def] of Object.entries(schema.$defs ?? {})) {
    defs[name] = def;
  }
  const { $defs: _drop, $schema: _s, ...rest } = schema;
  defs[title] = { ...rest, title };
  roots[title] = { $ref: `#/$defs/${title}` };
}

const root: JSONSchema = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  title: "RubatoProtocol",
  type: "object",
  properties: roots,
  additionalProperties: false,
  $defs: defs,
} as JSONSchema;

const header = `/* eslint-disable */\n// Generated by web/scripts/gen-types.ts from schema/protocol/*.schema.json. Do not edit.\n\n`;
const ts = await compile(root, "RubatoProtocol", { bannerComment: "", additionalProperties: false, strictIndexSignatures: true, unknownAny: true, format: false });
writeFileSync(out, header + ts);
console.log(`wrote ${out} from ${Object.keys(roots).length} root schemas and ${Object.keys(defs).length} definitions`);
